#!/usr/bin/env node
import { Command } from 'commander';
import { FileDiskReader } from '../fs/FileDiskReader.js';
import { MockInferenceAdapter } from '../ai/MockInferenceAdapter.js';
import { LlamaServerAdapter } from '../ai/LlamaServerAdapter.js';
import { RefactorCodeUseCase } from '../../application/use-cases/RefactorCodeUseCase.js';

const program = new Command();

program
  .name('clean-copilot')
  .description('Edge Clean Copilot — Specialized CLI for Clean Architecture & Edge Inference')
  .version('0.1.0');

program
  .command('refactor')
  .description('Refactor a TypeScript/JavaScript source file to adhere strictly to Clean Architecture')
  .argument('<file>', 'Path to the source file to refactor')
  .option('-m, --mock', 'Use deterministic mock inference engine (for offline testing/dry-run)', false)
  .option('-u, --url <url>', 'Llama-server base URL', 'http://127.0.0.1:8080')
  .option('-n, --model <model>', 'Model name identifier', 'edge-clean-copilot-q4_k_m')
  .action(async (file: string, options: { mock: boolean; url: string; model: string }) => {
    console.log(`\n======================================================`);
    console.log(`  Edge Clean Copilot — Clean Architecture Refactoring`);
    console.log(`======================================================\n`);
    console.log(`[Target File]  : ${file}`);
    console.log(`[Engine Mode]  : ${options.mock ? 'Mock Engine (Deterministic)' : `Llama-Server (${options.url})`}`);

    // 1. Read source file
    const fileReader = new FileDiskReader();
    const readResult = await fileReader.read(file);

    if (!readResult.success) {
      console.error(`\n[ERROR] ${readResult.error.message}`);
      process.exit(1);
    }

    // 2. Instantiate composition root
    const engine = options.mock
      ? new MockInferenceAdapter(50)
      : new LlamaServerAdapter({ baseUrl: options.url, modelName: options.model });

    const useCase = new RefactorCodeUseCase(engine);

    // 3. Execute use case
    console.log(`[Processing]   : Validating domain invariants & invoking inference...\n`);
    const result = await useCase.execute({
      filePath: file,
      fileContent: readResult.data
    });

    if (!result.success) {
      console.error(`[ERROR] (${result.error.name}) ${result.error.message}`);
      process.exit(1);
    }

    // 4. Output results
    console.log(`------------------------------------------------------`);
    console.log(`Refactored Output (Generated by ${result.data.modelUsed} in ${result.data.durationMs}ms):`);
    console.log(`------------------------------------------------------\n`);
    console.log(result.data.refactoredCode);
    console.log(`\n------------------------------------------------------`);
    console.log(`[Status] Success: ${result.data.originalLineCount} original lines processed.`);
    console.log(`------------------------------------------------------\n`);
  });

program.parse(process.argv);
