#!/usr/bin/env node
import { Command } from 'commander';
import { FileDiskReader } from '../fs/FileDiskReader.js';
import { FileDiskWriter } from '../fs/FileDiskWriter.js';
import { MockInferenceAdapter } from '../ai/MockInferenceAdapter.js';
import { LlamaServerAdapter } from '../ai/LlamaServerAdapter.js';
import { TerminalDiffFormatter } from './TerminalDiffFormatter.js';
import { RefactorCodeUseCase } from '../../application/use-cases/RefactorCodeUseCase.js';

interface RefactorCliOptions {
  readonly mock: boolean;
  readonly url: string;
  readonly model: string;
  readonly diff: boolean;
  readonly output?: string;
  readonly temperature?: string;
  readonly maxTokens?: string;
}

const program = new Command();

program
  .name('clean-copilot')
  .description('Edge Clean Copilot — Specialized CLI for Clean Architecture & Edge Inference')
  .version('0.1.0');

program
  .command('refactor')
  .description('Refactor a TypeScript/JavaScript source file to adhere strictly to Clean Architecture')
  .argument('<file>', 'Path to the source file to refactor')
  .option('-m, --mock', 'Use deterministic mock inference engine (for offline testing/dry-run)', false)
  .option('-u, --url <url>', 'Llama-server base URL', process.env.CLEAN_COPILOT_URL || 'http://192.168.6.35:8085')
  .option('-n, --model <model>', 'Model name identifier', process.env.CLEAN_COPILOT_MODEL || 'clean-copilot')
  .option('-d, --diff', 'Show unified terminal diff (+/-) comparing original vs refactored code', false)
  .option('-o, --output <path>', 'Write refactored code directly to the specified destination path')
  .option('-t, --temperature <number>', 'Inference temperature (e.g. 0.1 for deterministic, 0.7 for exploratory)')
  .option('--max-tokens <number>', 'Maximum tokens to generate')
  .action(async (file: string, options: RefactorCliOptions) => {
    console.log(`\n======================================================`);
    console.log(`  Edge Clean Copilot — Clean Architecture Refactoring`);
    console.log(`======================================================\n`);
    console.log(`[Target File]  : ${file}`);
    console.log(`[Engine Mode]  : ${options.mock ? 'Mock Engine (Deterministic)' : `Llama-Server (${options.url})`}`);

    const parsedTemp = options.temperature ? parseFloat(options.temperature) : undefined;
    const parsedMaxTokens = options.maxTokens ? parseInt(options.maxTokens, 10) : undefined;

    if (parsedTemp !== undefined) {
      console.log(`[Temperature]  : ${parsedTemp}`);
    }
    if (parsedMaxTokens !== undefined) {
      console.log(`[Max Tokens]   : ${parsedMaxTokens}`);
    }

    // 1. Read source file
    const fileReader = new FileDiskReader();
    const readResult = await fileReader.read(file);

    if (!readResult.success) {
      console.error(`\n[ERROR] ${readResult.error.message}`);
      process.exit(1);
    }

    // 2. Instantiate composition root
    const engine = options.mock
      ? new MockInferenceAdapter(50)
      : new LlamaServerAdapter({ baseUrl: options.url, modelName: options.model });

    const useCase = new RefactorCodeUseCase(engine);

    // 3. Execute use case
    console.log(`[Processing]   : Validating domain invariants & invoking inference...\n`);
    const result = await useCase.execute({
      filePath: file,
      fileContent: readResult.data,
      temperature: parsedTemp,
      maxTokens: parsedMaxTokens
    });

    if (!result.success) {
      console.error(`[ERROR] (${result.error.name}) ${result.error.message}`);
      process.exit(1);
    }

    // 4. Output results (Diff mode vs Full Code mode)
    if (options.diff) {
      const diffFormatter = new TerminalDiffFormatter();
      const diffResult = diffFormatter.format(readResult.data, result.data.refactoredCode, file);

      console.log(`------------------------------------------------------`);
      console.log(`Architectural Diff (Generated by ${result.data.modelUsed} in ${result.data.durationMs}ms):`);
      console.log(`------------------------------------------------------\n`);
      console.log(diffResult.formattedTerminalOutput);
      console.log(`\n------------------------------------------------------`);
      console.log(`[Diff Summary] : +${diffResult.addedCount} lines added, -${diffResult.removedCount} lines removed.`);
      console.log(`------------------------------------------------------\n`);
    } else {
      console.log(`------------------------------------------------------`);
      console.log(`Refactored Output (Generated by ${result.data.modelUsed} in ${result.data.durationMs}ms):`);
      console.log(`------------------------------------------------------\n`);
      console.log(result.data.refactoredCode);
      console.log(`\n------------------------------------------------------`);
      console.log(`[Status] Success: ${result.data.originalLineCount} original lines processed.`);
      console.log(`------------------------------------------------------\n`);
    }

    // 5. Persist output if requested
    if (options.output) {
      const fileWriter = new FileDiskWriter();
      const writeResult = await fileWriter.write(options.output, result.data.refactoredCode);

      if (!writeResult.success) {
        console.error(`\n[ERROR] Failed to save output: ${writeResult.error.message}`);
        process.exit(1);
      }

      console.log(`[Saved File]   : Refactored code written to "${options.output}"\n`);
    }
  });

program.parse(process.argv);
